import { ALUMNI_CONFIGS, SECTION_CONFIGS } from '../config.ts';
import type { Config } from '../types.ts';

const parseRedirects = (redirects: string[]) =>
  redirects.map((redirect) => `, www.${redirect}, ${redirect}`).join('');

const buildConfig = (config: Config[], snippet: string) => {
  return config.flatMap(({ cname, redirects = [] }) => [
    `# -------------- ${cname} --------------`,
    '',
    `www.${cname}.{$URL}${parseRedirects(redirects)} {`,
    '    import hardened_security',
    `    redir https://${cname}.{$URL}{uri} permanent`,
    '}',
    '',
    `${cname}.{$URL} {`,
    `    import ${snippet} ${cname}`,
    '}',
    '',
  ]);
};

export const buildCaddyfile = async () => {
  let lines = [
    '# GENERATED BY `buildCaddyfile.ts`',
    '',
    '# -------------- snippets --------------',
    '',
    '(esn_site) {',
    '    import hardened_security',
    '    encode',
    '    root * /srv/{args[0]}',
    '    try_files {path} /index.html',
    '    file_server',
    '}',
    '',
    '(esn_section) {',
    '    import hardened_security',
    '    encode',
    '    root * /srv/{args[0]}',
    '    @site file',
    '    handle @site {',
    '        file_server',
    '    }',
    '    @shared file {',
    '        root /srv/_shared',
    '        try_files {path}',
    '    }',
    '    handle @shared {',
    '        root * /srv/_shared',
    '        file_server',
    '    }',
    '    handle {',
    '        try_files {path} /index.html',
    '        file_server',
    '    }',
    '}',
    '',
    '# -------------- national --------------',
    '',
    'www.{$URL} {',
    '    import hardened_security',
    '    redir https://{$URL}{uri} permanent',
    '}',
    '',
    '{$URL} {',
    '    import esn_site @',
    '}',
    '',
  ];

  lines = lines.concat(buildConfig(ALUMNI_CONFIGS, 'esn_site'));
  lines = lines.concat(buildConfig(SECTION_CONFIGS, 'esn_section'));

  await Bun.write('./dist/Caddyfile', lines.join('\n'));
};
